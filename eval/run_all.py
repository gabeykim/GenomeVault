"""`make eval`: regenerate every proof (E1-E4) and docs/results.md from a clean run (BRIEF D item 5, gate G4).

Uses the real bucket partition and the live build when they exist; otherwise the stand-in partition and the
simulated P6 backend, and says so at the top of the write-up. The LLM attacker runs only with EVAL_LLM=1
(it spends API credit); cached answers replay offline.
"""
from __future__ import annotations

import datetime as dt
import json
import os

from eval import adaptive, gate, latency_cost, learning_curve, offline, redteam, wording
from eval.backends import BYTES_PER_BUCKET, MS, TOKENS, LiveBackend
from eval.universe import ROOT

DOCS = ROOT / "docs"
# Figures measured by hand, not by `make eval`. Each says who measured it, on what, and the set it covers.
MEASURED = [
    ("Label photos read on the laptop by a 7B vision model (demo set: 7 synthetic printed labels)",
     "7/7 correct, ~4 s each (10.6 s first call), no network",
     "Dhiaa, 2026-11-08 16:02: M4 Pro, Ollama qwen2.5vl:7b, GV_OCR=vlm, C's sample labels; D-029"),
]


def pct(x: float) -> str:
    return f"{x * 100:.0f}%"


def write_results(rt: dict, lc: dict, lat: dict, off: dict, wd: dict | None = None) -> str:
    st, j, bd = rt["single_topic"], rt["joint"], rt["bucket_design"]
    live = lc["backend"].startswith("live")
    L = []
    L.append("# GenomeVault results\n")
    L.append(f"Generated by `make eval` on {dt.date.today().isoformat()}. Synthetic data only (I1). "
             "Every number below is regenerated from a clean run; the JSON is in `eval/results/`.\n")
    L.append("> **Status.** Bucket partition: `" + rt["partition"] + "`. Backend: **" + lc["backend"] + "**. "
             + ("E2 and E4 ran on the integrated router, knowledge base and ledger; modules named \"mock\" in the backend are still "
                "stand-ins. E1 and E3 still use the simulated wire and backend. In demo mode the cloud replays `mocks/cloud_cache/`; "
                "until that cache is recorded no answer reaches the knowledge base, so the live learning curve and warm-offline "
                "numbers understate the design." if live else
                "Until B's router merges (G2), E2–E4 run on a simulation of PLAN P6 and E1 on a simulated wire; "
                "counts follow from the design, latency and tokens are modelled. Re-run at G4 on the integrated build.") + "\n")
    ps = rt.get("partition_stats", {})
    if ps.get("fallback_reason"):
        L.append(f"> **Partition fallback.** B's file exists but {ps['fallback_reason']}; using D's stand-in.\n")
    elif rt["partition"].startswith("real") and ps.get("partition_keys_without_prior", 0) > 0:
        L.append(f"> **Coverage warning.** {ps['partition_keys_without_prior']} of {ps['raw_keys']} partition keys have no synthetic prior "
                 "and get the median. Synthetic patients only ask about keys with priors, which inflates the statistical attacker. "
                 "Extend `eval/fixtures/universe_v1.json` to every partition key before quoting E1 statistical numbers.\n")
    if ps.get("phenotype_split_topics"):
        fb = rt["single_topic"]["fixed_buckets"]
        splits = "; ".join(f"`{g}` in {', '.join(ids)}" for g, ids in ps["phenotype_split_topics"].items())
        L.append(f"> **Bucket-identity leak.** Phenotype variants of the same topic sit in different buckets ({splits}). "
                 "Their outbound text is identical, but which bucket leaves tells an observer which variant applies, so "
                 f"guessing the topic also reveals the genotype (I3). Measured: {pct(fb.get('phenotype_via_bucket', 0))} of "
                 "synthetic patients. Keeping every variant of a topic in one bucket closes it.\n")
    if ps.get("raw_keys_with_phenotype"):
        L.append(f"> **Key detail.** {ps['raw_keys_with_phenotype']} of {ps['raw_keys']} partition keys name a phenotype and "
                 f"{ps['raw_keys_with_threshold_or_dose']} a lab threshold or dose. Evals measure generalized topics; whether those raw "
                 "keys ever appear in outbound text is B's leakage check (I3).\n")
    g = gate.check(rt, lc, lat, off, wd)
    s = gate.summary(g)
    L.append(f"## G4 gate check: {s['PASS']} pass, {s['WARN']} warn, {s['FAIL']} fail\n")
    L.append("`python -m eval.gate` re-runs this after `make eval` and exits non-zero on any FAIL. Don't quote a FAIL claim.\n")
    L.append("| | Claim | Result |")
    L.append("| --- | --- | --- |")
    for c in g:
        L.append(f"| {c['status']} | {c['claim']} | {c['value']} |")
    L.append("")
    L.append("## E1 · Red team: can an attacker who sees all outbound traffic recover the real question?\n")
    L.append("![red team](charts/redteam.svg)\n")
    L.append(f"{rt['trials']} synthetic patients, {rt['asks']} asks each. Real topic guessed:\n")
    L.append("| Condition | Repeat-ask attacker | Statistical attacker | Condition area guessed | A real med inferred | Genotype leaked |")
    L.append("| --- | --- | --- | --- | --- | --- |")
    names = {"naive": "Naive (full question + profile)", "random_decoys": "Generalized + 7 random decoys, fresh each ask",
             "random_decoys_1ask": "Random decoys, asked only once", "fixed_buckets": "Generalized + fixed bucket of 8 (GenomeVault)"}
    for k, n in names.items():
        r = st[k]
        L.append(f"| {n} | {pct(r['intersection'])} | {pct(r['statistical'])} | {pct(r['domain'])} | {pct(r['med_inferred'])} | {pct(r['genotype_leaked'])} |")
    L.append(f"\nBaselines: 1 in 8 = 12.5%; guessing the most common clinical area with no traffic = {pct(st['_baselines']['domain_majority_guess'])}.\n")
    L.append(f"**Reading it.** Naive leaks everything. Random decoys look fine once ({pct(st['random_decoys_1ask']['intersection'])}) "
             f"but collapse when a question repeats, because only the real topic survives every ask. Fixed buckets send the "
             f"same 8 every time, so repetition reveals nothing: the repeat-ask attacker sits near 1 in 8 "
             f"({pct(st['fixed_buckets']['intersection'])}). The **statistical attacker** is the honest number: by betting on the most "
             f"common topic in the bucket it reaches {pct(st['fixed_buckets']['statistical'])}. The partition's ceiling for that attacker "
             f"is {pct(bd['stat_attacker_ceiling'])}; it falls to 12.5% only when topics in a bucket are equally common, which is a "
             "bucket-design target for B. Genotypes, ages and lab values never leave in generalized topics.\n")
    L.append("### Joint inference: do simultaneous buckets reveal the condition?\n")
    L.append("![joint inference](charts/joint.svg)\n")
    L.append("| Sending pattern | Condition guessed | Real topics recovered |")
    L.append("| --- | --- | --- |")
    jn = {"same_session": "All buckets in one session", "separate_cover_linkable": "Separate sessions + 2 cover buckets each, same device (linkable)",
          "separate_cover_unlinkable": "Separate sessions + cover, unlinkable (needs relay)"}
    for k, n in jn.items():
        L.append(f"| {n} | {pct(j[k]['scenario'])} | {pct(j[k]['key_recall'])} |")
    L.append(f"\nBaseline: guessing the most common condition = {pct(j['_baselines']['scenario_majority_guess'])} "
             f"({j['_baselines']['n_scenarios']} synthetic conditions). The attacker is Bayesian and knows the public cover rate.\n")
    L.append("**Reading it.** Sending a discharge bundle in one session lets an attacker name the condition about "
             f"{j['same_session']['scenario'] / j['_baselines']['scenario_majority_guess']:.1f}x more often than a blind guess (D-006). "
             "Separate sessions plus cover buckets bring it close to the blind guess. Linking by IP still helps the attacker a little, "
             "which is why the relay layer stays on the roadmap (README limitations).\n")
    L.append("### LLM attacker\n")
    llm = rt["llm"]
    if llm.get("status") == "ran":
        L.append(f"Model `{llm['model']}`: naive {pct(llm['naive'])}, random decoys {pct(llm['random_decoys'])}, fixed buckets {pct(llm['fixed_buckets'])}.\n")
    else:
        L.append(f"Not run: {llm['status']}. `EVAL_LLM=1 make eval` runs it; answers are cached under `eval/cache/llm/`. "
                 "The deterministic attackers above are the stronger test.\n")
    L.append("## E2 · Learning curve\n")
    L.append("![learning curve](charts/learning_curve.svg)\n")
    L.append(f"20 scripted questions from an empty knowledge base: **{lc['total_cloud_calls']} cloud calls in total**, "
             f"{pct(lc['local_share'])} answered on device. First five questions: {lc['cloud_calls_first5']} calls; last five: "
             f"{lc['cloud_calls_last5']}. Q19 (a related follow-up) is a knowledge-base hit with 0 bytes sent"
             f"{'' if lc['repeat_q19_is_local'] else ' — FAILED'}.\n")
    L.append("## E3 · Latency, cloud usage and coverage\n")
    L.append("![latency and cost](charts/latency_cost.svg)\n")
    L.append("| Mode | Median latency | Cloud calls | Cloud tokens | Personal fields sent | Coverage |")
    L.append("| --- | --- | --- | --- | --- | --- |")
    for m, n in (("local_only", "Local only"), ("cloud_only", "Cloud only (naive)"), ("hybrid", "Hybrid (GenomeVault)")):
        r = lat["modes"][m]
        L.append(f"| {n} | {r['median_latency_ms']:.0f} ms | {r['cloud_calls']} | {r['cloud_tokens']:,} | {r['personal_fields_sent']} | {pct(r['coverage'])} |")
    miss = lat["modes"]["hybrid"].get("not_fully_answered", [])
    if miss:
        L.append(f"\nHybrid could not fully answer {', '.join(miss)}: a key they need is outside the bucket partition, so it took the honest no-data path (I5).")
    L.append(f"\nLatency and tokens are **{lat['latency']}** (constants: {json.dumps(MS)}, tokens {json.dumps(TOKENS)}, "
             f"{BYTES_PER_BUCKET} bytes per bucket). Coverage is the share of questions reaching their expected answer state, "
             f"not graded quality: {lat['quality']}. Note the honest trade-off: hybrid makes far fewer calls, but each bucket carries 8 "
             "questions, so token savings are smaller than call savings.\n")
    lv = lat.get("live")
    if lv:
        nd, dd = lv["no_delay"], lv["default_delay"]
        L.append(f"**Live hybrid ({nd['backend']}).** No delays: median {nd['median_latency_ms']:.0f} ms per question"
                 + (f", {nd['median_latency_ms_when_sent']:.0f} ms when buckets are sent" if nd["median_latency_ms_when_sent"] is not None else "")
                 + f"; {nd['cloud_calls']} cloud calls, {nd['bytes_out']:,} bytes, {nd['personal_fields_sent']} personal fields.")
        if isinstance(dd, dict):
            L.append(f" With B's default P6.4 delays (`GV_DELAY_S={dd['GV_DELAY_S']}`): median {dd['median_latency_ms']:.0f} ms"
                     + (f", {dd['median_latency_ms_when_sent']:.0f} ms when sent" if dd["median_latency_ms_when_sent"] is not None else "")
                     + f"; the whole script took {dd['wall_s']:.0f} s vs {nd['wall_s']:.1f} s.")
        else:
            L.append(f" With delays: {dd}.")
        L.append(" Demo mode replays the cache, so these times exclude real cloud round trips.\n")
    L.append("## E4 · Offline\n")
    L.append("![offline](charts/offline.svg)\n")
    L.append(f"Wi-Fi off: **{off['cold_answered']}/20** answered with content on a cold device, **{off['warm_answered']}/20** after one "
             f"online session{', **' + str(off['synced_answered']) + '/20** after a full knowledge-pack sync (B-010)' if off.get('synced_answered') is not None else ''}. Every other question gets an honest \"no data for this combination; ask your pharmacist\" "
             f"({off['matches_offline_state_cold']}/20 cold answers match the predicted state). Nothing is sent offline.\n")
    if off.get("cold_router_answered") is not None:
        L.append(f"Two readings (A-016). **User-visible** counts a covering local flag or curated note, because it's on the screen: "
                 f"{off['cold_answered']}/20 cold, {off['synced_answered']}/20 after a pack sync. **Strict** counts only the router's own "
                 f"`known` (a stored fact or a local-only flag): {off['cold_router_answered']}/20 cold, "
                 f"{off.get('synced_router_answered')}/20 after a pack sync.\n")
    L.append("## I7 wording filter red team\n")
    if wd and wd.get("status") == "ran":
        L.append(f"D's adversarial cases (`eval/fixtures/wording_cases.json`) against B's `wording_problems` (B-013): "
                 f"**{wd['caught']}/{wd['should_reject']}** texts that break I7 were rejected; "
                 f"{wd['false_alarms']}/{wd['should_accept']} neutral texts were wrongly rejected "
                 f"(plus {wd['by_design_rejected']} rejected by design for containing the four letters s-a-f-e).\n")
        L.append("| Family | Caught |")
        L.append("| --- | --- |")
        for fam, v in wd["by_family"].items():
            L.append(f"| {fam.replace('_', ' ')} | {v['caught']}/{v['of']} |")
        L.append("\nThese are hand-written adversarial texts, not measured cloud output: they show where the last-line filter "
                 "has gaps, not how often real answers fall into them. A miss would let an answer that breaks I7 become a "
                 "stored fact; a false alarm only turns that key into `no_data`.\n")
    else:
        L.append(f"Not run: {(wd or {}).get('status', 'not requested')}. It runs once B's validator is in the build.\n")
    L.append("## Method and limits\n")
    L.append("- Synthetic priors, domains and clusters: `eval/fixtures/universe_v1.json` (illustrative, not real prescription data).\n"
             "- Attackers see only outbound traffic plus public knowledge (partition, priors, clusters, cover rate).\n"
             "- Network metadata (IP, timing, account) is out of scope today; the linkable rows show what it costs.\n"
             "- Demo, not medical advice.\n")
    return "\n".join(L) + "\n"


def write_numbers(rt: dict, lc: dict, lat: dict, off: dict, wd: dict | None) -> str:
    """slides/numbers.md: every figure the pitch and judge Q&A quote, generated, with its gate status."""
    g = {c["id"]: c["status"] for c in gate.check(rt, lc, lat, off, wd)}
    st, j, bd = rt["single_topic"], rt["joint"], rt["bucket_design"]
    h, co = lat["modes"]["hybrid"], lat["modes"]["cloud_only"]
    rows = [
        ("Naive sending: real question recovered", pct(st["naive"]["intersection"]), "E1a"),
        ("Random decoys after 3 asks: real question recovered", pct(st["random_decoys"]["intersection"]), "E1b"),
        ("Fixed buckets: repeat-ask attacker", pct(st["fixed_buckets"]["intersection"]), "E1c"),
        ("Fixed buckets: statistical attacker", pct(st["fixed_buckets"]["statistical"]), "E1d"),
        ("Design ceiling for the statistical attacker", pct(bd["stat_attacker_ceiling"]), "E1d"),
        ("Genotype / age / lab values leaked in generalized traffic", pct(st["fixed_buckets"]["genotype_leaked"]), "I3a"),
        ("Condition guessed, all buckets in one session", pct(j["same_session"]["scenario"]), "D-006"),
        ("Condition guessed, separate sessions + cover", pct(j["separate_cover_linkable"]["scenario"]), "D-006"),
        ("Blind guess of the condition", pct(j["_baselines"]["scenario_majority_guess"]), "D-006"),
        ("Cloud calls for the 20 scripted questions", str(lc["total_cloud_calls"]), "E2a"),
        ("Share answered on device", pct(lc["local_share"]), "E2a"),
        ("Personal fields sent: hybrid vs cloud-only", f"{h['personal_fields_sent']} vs {co['personal_fields_sent']}", "E3a"),
        ("Offline: answered on a cold device", f"{off['cold_answered']}/20", "E4a"),
        ("Offline: answered after one online session", f"{off['warm_answered']}/20", "E4a"),
        ("Offline: after a knowledge-pack sync", f"{off.get('synced_answered')}/20", "E4c"),
        ("Offline, strict reading (stored answers only): cold / synced",
         f"{off.get('cold_router_answered')}/20 / {off.get('synced_router_answered')}/20", "E4d"),
    ]
    if wd and wd.get("status") == "ran":
        rows.append(("Wording filter: adversarial texts caught", f"{wd['caught']}/{wd['should_reject']}", "I7b"))
    L = ["# Slide numbers", "",
         f"Generated by `make eval` on {dt.date.today().isoformat()} from `eval/results/`. Partition `{rt['partition']}`, "
         f"backend **{lc['backend']}**. Quote only rows marked PASS; re-run `make eval` before rehearsal.", "",
         "| Figure | Value | Gate |", "| --- | --- | --- |"]
    L += [f"| {a} | {b} | {g.get(c, '—')} ({c}) |" for a, b, c in rows]
    L += ["", "## Measured by hand (not from `make eval`)", "",
          "Quote these with their scope; they are not a general accuracy claim.", "",
          "| Figure | Value | Source |", "| --- | --- | --- |"]
    L += [f"| {a} | {b} | {c} |" for a, b, c in MEASURED]
    return "\n".join(L) + "\n"


def write_adaptive(ad: dict, core: dict | None = None) -> str:
    """docs/results.md section for D-040 part 5. Reported apart from the core: no gate check, no slide figure."""
    L = ["", "## D-040 · Adaptive questions (flags off by default; reported separately from the core)", "",
         "Behind `GV_FUZZY` (A's typo suggestions) and `GV_TAIL` (B's long-tail partition). Nothing here changes a gate "
         "check or a figure in `slides/numbers.md`.", ""]
    t = ad["typos"]
    L.append("### Typo suggestions (D's 20-item set, `eval/fixtures/typo_set.json`)\n")
    if t["status"] == "ran":
        L += [f"- Intended name among the choices: **{t['correct']}/{t['n']}** ({t['assumed']} assumed with an undo, {t['asked']} asked, {t['no_suggestion']} with no suggestion).",
              f"- Silent wrong substitutions: **{t['silent_wrong']}**. Look-alike names assumed instead of asked: **{t['lookalike_assumed']}**. Both must be 0 (I4).",
              "- D wrote the set independently of A's own cases; every intended name is in A's lexicon or look-alike list. Multi-word names are a known gap (A).", ""]
    else:
        L += [f"Not run: {t['reason']}.", ""]
    tl = ad["tail"]
    L.append(f"### Long-tail partition (E1 on `data/buckets/{tl.get('partition', 'tail')}.json`, the version `core.decoys.TAIL_VERSION` ships)\n")
    if tl["status"] == "ran":
        sm = tl["sensitivity_unseen_median"]
        L += [f"{tl['buckets']} fixed buckets of 8 ({tl['keys']} keys), {tl['n']} synthetic patients, {tl['asks']} asks each. Real pair guessed:\n",
              "| Attacker | Long tail | Core (v5, for comparison) |", "| --- | --- | --- |",
              f"| Repeat-ask | {pct(tl['repeat_ask'])} | {pct(core['intersection']) if core else 'see E1'} |",
              f"| Statistical (bets on the most common pair in the group) | **{pct(tl['statistical'])}** (ceiling {pct(tl['stat_attacker_ceiling'])}) | {pct(core['statistical']) if core else 'see E1'} |", "",
              (f"**Weaker than the core.** {tl['partition']} buckets are a seeded shuffle with no frequency balancing, so a bucket often holds "
               f"one pair with a common drug among rare ones, and the statistical attacker bets on it. " if tl['statistical'] > 0.3 else
               f"**Frequency-tiered** ({tl['partition']}, B-068): keys are grouped by how common their drugs are, so no pair stands out in "
               f"its group of 8. ") +
              f"Tail pairs have no priors of their own, "
              f"so these use synthetic ones: each drug's summed priors from D's universe file, multiplied for a pair, with drugs and labs "
              f"the file doesn't list set to the smallest known value. With them set to the median instead, the statistical attacker gets {pct(sm['statistical'])}. "
              "The repeat-ask attacker stays near 1 in 8 either way, because the bucket is fixed. " +
              ("Say plainly: common questions get the strongest protection; rare ones are still hidden in a fixed group of 8, "
               "measured separately." if core and tl["statistical"] > core["statistical"] + 0.05 else
               "On this measure rare questions are protected about as well as common ones; they are still reported separately."), ""]
    else:
        L += [f"Not run: {tl['reason']}.", ""]
    return "\n".join(L) + "\n"


def main():
    be = LiveBackend() if LiveBackend.available() else None
    rt = redteam.run(llm=os.environ.get("EVAL_LLM") == "1")
    lc = learning_curve.run(be)
    lat = latency_cost.run()
    off = offline.run()
    wd = wording.run()
    DOCS.mkdir(exist_ok=True)
    ad = adaptive.run()
    (DOCS / "results.md").write_text(write_results(rt, lc, lat, off, wd) + write_adaptive(ad, rt["single_topic"]["fixed_buckets"]))
    (ROOT / "slides" / "numbers.md").write_text(write_numbers(rt, lc, lat, off, wd))
    print(f"wrote docs/results.md and docs/charts/*.svg (partition {rt['partition']}, backend {lc['backend']})")


if __name__ == "__main__":
    main()
