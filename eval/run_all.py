"""`make eval`: regenerate every proof (E1-E4) and docs/results.md from a clean run (BRIEF D item 5, gate G4).

Uses the real bucket partition and the live build when they exist; otherwise the stand-in partition and the
simulated P6 backend, and says so at the top of the write-up. The LLM attacker runs only with EVAL_LLM=1
(it spends API credit); cached answers replay offline.
"""
from __future__ import annotations

import datetime as dt
import json
import os

from eval import latency_cost, learning_curve, offline, redteam
from eval.backends import BYTES_PER_BUCKET, MS, TOKENS, LiveBackend
from eval.universe import ROOT

DOCS = ROOT / "docs"


def pct(x: float) -> str:
    return f"{x * 100:.0f}%"


def write_results(rt: dict, lc: dict, lat: dict, off: dict) -> str:
    st, j, bd = rt["single_topic"], rt["joint"], rt["bucket_design"]
    live = lc["backend"].startswith("live")
    L = []
    L.append("# GenomeVault results\n")
    L.append(f"Generated by `make eval` on {dt.date.today().isoformat()}. Synthetic data only (I1). "
             "Every number below is regenerated from a clean run; the JSON is in `eval/results/`.\n")
    L.append("> **Status.** Bucket partition: `" + rt["partition"] + "`. Backend: **" + lc["backend"] + "**. "
             + ("E2 and E4 ran on the integrated router, knowledge base and ledger; modules named \"mock\" in the backend are still "
                "stand-ins. E1 and E3 still use the simulated wire and backend. In demo mode the cloud replays `mocks/cloud_cache/`; "
                "until that cache is recorded no answer reaches the knowledge base, so the live learning curve and warm-offline "
                "numbers understate the design." if live else
                "Until B's router merges (G2), E2–E4 run on a simulation of PLAN P6 and E1 on a simulated wire; "
                "counts follow from the design, latency and tokens are modelled. Re-run at G4 on the integrated build.") + "\n")
    ps = rt.get("partition_stats", {})
    if ps.get("fallback_reason"):
        L.append(f"> **Partition fallback.** B's file exists but {ps['fallback_reason']}; using D's stand-in.\n")
    elif rt["partition"].startswith("real") and ps.get("partition_keys_without_prior", 0) > 0:
        L.append(f"> **Coverage warning.** {ps['partition_keys_without_prior']} of {ps['raw_keys']} partition keys have no synthetic prior "
                 "and get the median. Synthetic patients only ask about keys with priors, which inflates the statistical attacker. "
                 "Extend `eval/fixtures/universe_v1.json` to every partition key before quoting E1 statistical numbers.\n")
    if ps.get("raw_keys_with_phenotype"):
        L.append(f"> **Key detail.** {ps['raw_keys_with_phenotype']} of {ps['raw_keys']} partition keys name a phenotype and "
                 f"{ps['raw_keys_with_threshold_or_dose']} a lab threshold or dose. Evals measure generalized topics; whether those raw "
                 "keys ever appear in outbound text is B's leakage check (I3).\n")
    L.append("## E1 · Red team: can an attacker who sees all outbound traffic recover the real question?\n")
    L.append("![red team](charts/redteam.svg)\n")
    L.append(f"{rt['trials']} synthetic patients, {rt['asks']} asks each. Real topic guessed:\n")
    L.append("| Condition | Repeat-ask attacker | Statistical attacker | Condition area guessed | A real med inferred | Genotype leaked |")
    L.append("| --- | --- | --- | --- | --- | --- |")
    names = {"naive": "Naive (full question + profile)", "random_decoys": "Generalized + 7 random decoys, fresh each ask",
             "random_decoys_1ask": "Random decoys, asked only once", "fixed_buckets": "Generalized + fixed bucket of 8 (GenomeVault)"}
    for k, n in names.items():
        r = st[k]
        L.append(f"| {n} | {pct(r['intersection'])} | {pct(r['statistical'])} | {pct(r['domain'])} | {pct(r['med_inferred'])} | {pct(r['genotype_leaked'])} |")
    L.append(f"\nBaselines: 1 in 8 = 12.5%; guessing the most common clinical area with no traffic = {pct(st['_baselines']['domain_majority_guess'])}.\n")
    L.append(f"**Reading it.** Naive leaks everything. Random decoys look fine once ({pct(st['random_decoys_1ask']['intersection'])}) "
             f"but collapse when a question repeats, because only the real topic survives every ask. Fixed buckets send the "
             f"same 8 every time, so repetition reveals nothing: the repeat-ask attacker sits near 1 in 8 "
             f"({pct(st['fixed_buckets']['intersection'])}). The **statistical attacker** is the honest number: by betting on the most "
             f"common topic in the bucket it reaches {pct(st['fixed_buckets']['statistical'])}. The partition's ceiling for that attacker "
             f"is {pct(bd['stat_attacker_ceiling'])}; it falls to 12.5% only when topics in a bucket are equally common, which is a "
             "bucket-design target for B. Genotypes, ages and lab values never leave in generalized topics.\n")
    L.append("### Joint inference: do simultaneous buckets reveal the condition?\n")
    L.append("![joint inference](charts/joint.svg)\n")
    L.append("| Sending pattern | Condition guessed | Real topics recovered |")
    L.append("| --- | --- | --- |")
    jn = {"same_session": "All buckets in one session", "separate_cover_linkable": "Separate sessions + 2 cover buckets each, same device (linkable)",
          "separate_cover_unlinkable": "Separate sessions + cover, unlinkable (needs relay)"}
    for k, n in jn.items():
        L.append(f"| {n} | {pct(j[k]['scenario'])} | {pct(j[k]['key_recall'])} |")
    L.append(f"\nBaseline: guessing the most common condition = {pct(j['_baselines']['scenario_majority_guess'])} "
             f"({j['_baselines']['n_scenarios']} synthetic conditions). The attacker is Bayesian and knows the public cover rate.\n")
    L.append("**Reading it.** Sending a discharge bundle in one session lets an attacker name the condition about "
             f"{j['same_session']['scenario'] / j['_baselines']['scenario_majority_guess']:.1f}x more often than a blind guess (D-006). "
             "Separate sessions plus cover buckets bring it close to the blind guess. Linking by IP still helps the attacker a little, "
             "which is why the relay layer stays on the roadmap (README limitations).\n")
    L.append("### LLM attacker\n")
    llm = rt["llm"]
    if llm.get("status") == "ran":
        L.append(f"Model `{llm['model']}`: naive {pct(llm['naive'])}, random decoys {pct(llm['random_decoys'])}, fixed buckets {pct(llm['fixed_buckets'])}.\n")
    else:
        L.append(f"Not run: {llm['status']}. `EVAL_LLM=1 make eval` runs it; answers are cached under `eval/cache/llm/`. "
                 "The deterministic attackers above are the stronger test.\n")
    L.append("## E2 · Learning curve\n")
    L.append("![learning curve](charts/learning_curve.svg)\n")
    L.append(f"20 scripted questions from an empty knowledge base: **{lc['total_cloud_calls']} cloud calls in total**, "
             f"{pct(lc['local_share'])} answered on device. First five questions: {lc['cloud_calls_first5']} calls; last five: "
             f"{lc['cloud_calls_last5']}. Q19 (a related follow-up) is a knowledge-base hit with 0 bytes sent"
             f"{'' if lc['repeat_q19_is_local'] else ' — FAILED'}.\n")
    L.append("## E3 · Latency, cloud usage and coverage\n")
    L.append("![latency and cost](charts/latency_cost.svg)\n")
    L.append("| Mode | Median latency | Cloud calls | Cloud tokens | Personal fields sent | Coverage |")
    L.append("| --- | --- | --- | --- | --- | --- |")
    for m, n in (("local_only", "Local only"), ("cloud_only", "Cloud only (naive)"), ("hybrid", "Hybrid (GenomeVault)")):
        r = lat["modes"][m]
        L.append(f"| {n} | {r['median_latency_ms']:.0f} ms | {r['cloud_calls']} | {r['cloud_tokens']:,} | {r['personal_fields_sent']} | {pct(r['coverage'])} |")
    miss = lat["modes"]["hybrid"].get("not_fully_answered", [])
    if miss:
        L.append(f"\nHybrid could not fully answer {', '.join(miss)}: a key they need is outside the bucket partition, so it took the honest no-data path (I5).")
    L.append(f"\nLatency and tokens are **{lat['latency']}** (constants: {json.dumps(MS)}, tokens {json.dumps(TOKENS)}, "
             f"{BYTES_PER_BUCKET} bytes per bucket). Coverage is the share of questions reaching their expected answer state, "
             f"not graded quality: {lat['quality']}. Note the honest trade-off: hybrid makes far fewer calls, but each bucket carries 8 "
             "questions, so token savings are smaller than call savings.\n")
    L.append("## E4 · Offline\n")
    L.append("![offline](charts/offline.svg)\n")
    L.append(f"Wi-Fi off: **{off['cold_answered']}/20** answered with content on a cold device, **{off['warm_answered']}/20** after one "
             f"online session{', **' + str(off['synced_answered']) + '/20** after a full knowledge-pack sync (B-010)' if off.get('synced_answered') is not None else ''}. Every other question gets an honest \"no data for this combination; ask your pharmacist\" "
             f"({off['matches_offline_state_cold']}/20 cold answers match the predicted state). Nothing is sent offline.\n")
    L.append("## Method and limits\n")
    L.append("- Synthetic priors, domains and clusters: `eval/fixtures/universe_v1.json` (illustrative, not real prescription data).\n"
             "- Attackers see only outbound traffic plus public knowledge (partition, priors, clusters, cover rate).\n"
             "- Network metadata (IP, timing, account) is out of scope today; the linkable rows show what it costs.\n"
             "- Demo, not medical advice.\n")
    return "\n".join(L) + "\n"


def main():
    be = LiveBackend() if LiveBackend.available() else None
    rt = redteam.run(llm=os.environ.get("EVAL_LLM") == "1")
    lc = learning_curve.run(be)
    lat = latency_cost.run()
    off = offline.run()
    DOCS.mkdir(exist_ok=True)
    (DOCS / "results.md").write_text(write_results(rt, lc, lat, off))
    print(f"wrote docs/results.md and docs/charts/*.svg (partition {rt['partition']}, backend {lc['backend']})")


if __name__ == "__main__":
    main()
